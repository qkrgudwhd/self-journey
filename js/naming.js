// ---------- ② 수리 4격 (원형이정) ----------
// 숫자 한자 특례(수리성명학 관례): 획수 대신 수의 값 (기본 적용)
const NUMERAL_HANJA = { '一':1,'二':2,'三':3,'四':4,'五':5,'六':6,'七':7,'八':8,'九':9,'十':10 };

function hanjaStrokes(ch, opts = {}) {
  const useNumeral = opts.numeralRule !== false;
  if (useNumeral && ch in NUMERAL_HANJA) return NUMERAL_HANJA[ch];
  const e = HANJA_DB[ch];
  if (!e) return null;
  return opts.useFilhoek ? e[1] : e[0];      // 기본: 원획(성명학 표준)
}

function suriGrade(n) {
  const k = ((n - 1) % 81) + 1;              // 81 초과 시 81을 뺀 수로 봄 (관례)
  const [grade, name, desc] = SURI_81[k];
  return { num: n, reduced: k, grade, name, desc };
}

/**
 * 한자 이름 수리 분석
 * surname: 성 한자 배열 (복성 지원, 예: ['南','宮'])
 * given: 이름 한자 배열 (1~3자)
 * strokesOverride: {한자: 획수} — 사용자가 직접 고친 획수
 */
function analyzeSuri(surname, given, opts = {}) {
  const all = [...surname, ...given];
  const detail = [];
  for (const ch of all) {
    let s = (opts.strokesOverride && opts.strokesOverride[ch]) || hanjaStrokes(ch, opts);
    if (s === null) return { error: `'${ch}' 획수를 찾을 수 없습니다. 직접 입력해 주세요.` };
    detail.push({ char: ch, strokes: s });
  }
  const sum = arr => arr.reduce((a, c) => a + c.strokes, 0);
  const sChars = detail.slice(0, surname.length);
  const gChars = detail.slice(surname.length);
  if (gChars.length === 0) return { error: '이름 한자가 필요합니다.' };

  // 원형이정: 元=이름만(초년) 亨=성+이름첫자(청년) 利=성+이름끝자(장년) 貞=전체(총운)
  const won   = sum(gChars);
  const hyung = sum(sChars) + gChars[0].strokes;
  const li    = gChars.length === 1
              ? sum(sChars) + gChars[0].strokes          // 외자 이름: 형격과 동일 관례
              : sum(sChars) + gChars[gChars.length - 1].strokes;
  const jung  = sum(detail);

  return {
    chars: detail,
    gyeok: [
      { key: '원격(元)', period: '초년(0~20대)',  ...suriGrade(won) },
      { key: '형격(亨)', period: '청·장년(주운)', ...suriGrade(hyung) },
      { key: '이격(利)', period: '중·장년(부운)', ...suriGrade(li) },
      { key: '정격(貞)', period: '총운(일생)',    ...suriGrade(jung) },
    ],
  };
}

// 독음으로 한자 후보 검색 (UI용): '형' → [{char, strokes, reads}...]
function searchHanjaByReading(reading) {
  const list = HANJA_BY_READING[reading] || [];
  return list.map(ch => ({ char: ch, strokes: HANJA_DB[ch][0], filhoek: HANJA_DB[ch][1], reads: HANJA_DB[ch][2] }))
             .sort((a, b) => a.strokes - b.strokes);
}

