// ---------- ① 소리오행 ----------
const CHO = ['ㄱ','ㄲ','ㄴ','ㄷ','ㄸ','ㄹ','ㅁ','ㅂ','ㅃ','ㅅ','ㅆ','ㅇ','ㅈ','ㅉ','ㅊ','ㅋ','ㅌ','ㅍ','ㅎ'];
// 초성 → 오행 (0목 1화 2토 3금 4수)
const CHO_ELEM = { 'ㄱ':0,'ㄲ':0,'ㅋ':0, 'ㄴ':1,'ㄷ':1,'ㄸ':1,'ㄹ':1,'ㅌ':1,
                   'ㅇ':2,'ㅎ':2, 'ㅅ':3,'ㅆ':3,'ㅈ':3,'ㅉ':3,'ㅊ':3, 'ㅁ':4,'ㅂ':4,'ㅃ':4,'ㅍ':4 };
const N_ELEM   = ['목','화','토','금','수'];
const N_ELEM_H = ['木','火','土','金','水'];

function choseong(ch) {
  const code = ch.charCodeAt(0) - 0xAC00;
  if (code < 0 || code > 11171) return null;
  return CHO[Math.floor(code / 588)];
}

// 두 오행 관계: 상생(a가 b를 낳음/ b가 a를 낳음) · 비화(같음) · 상극
function elemRelation(a, b) {
  if (a === b) return { rel: '비화', good: true };
  if ((a + 1) % 5 === b) return { rel: '상생', good: true };   // a → b 생
  if ((b + 1) % 5 === a) return { rel: '상생', good: true };   // b → a 생
  return { rel: '상극', good: false };
}

// 이름(한글) → 소리오행 분석
function analyzeSoriOhaeng(hangulName) {
  const chars = [...hangulName.replace(/\s/g, '')];
  const elems = [];
  for (const ch of chars) {
    const cho = choseong(ch);
    if (!cho) return { error: `'${ch}'는 한글이 아닙니다.` };
    elems.push({ char: ch, cho, elem: CHO_ELEM[cho],
                 elemName: N_ELEM[CHO_ELEM[cho]], elemHanja: N_ELEM_H[CHO_ELEM[cho]] });
  }
  const flows = [];
  let goodCnt = 0;
  for (let i = 0; i + 1 < elems.length; i++) {
    const r = elemRelation(elems[i].elem, elems[i + 1].elem);
    flows.push({ pair: elems[i].char + '·' + elems[i + 1].char,
                 pairElem: elems[i].elemName + '→' + elems[i + 1].elemName, ...r });
    if (r.good) goodCnt++;
  }
  const allGood = flows.length > 0 && goodCnt === flows.length;
  const anyBad = flows.some(f => !f.good);
  const verdict = allGood ? '길(吉) — 오행이 순하게 이어집니다'
                : !anyBad ? '평(平)'
                : goodCnt === 0 ? '흉(凶) — 오행이 서로 부딪칩니다'
                : '반길반흉 — 상생과 상극이 섞여 있습니다';
  return { chars: elems, flows, verdict, goodCount: goodCnt, totalFlows: flows.length };
}

