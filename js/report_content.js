// ---------- 도형(무의식) × 성향검사(의식) 교차 ----------
const SHAPE_EXPECT = {
  square:  { letters:['S','J'], label:'체계·안정' },
  triangle:{ letters:['E','T','J'], label:'주도·결단' },
  circle:  { letters:['F'], label:'공감·관계' },
  zigzag:  { letters:['N','P'], label:'창의·개방' },
  rect:    { letters:[], label:'전환·탐색' },
};

function crossShapeMbti(shapeKey, mbtiType) {
  const exp = SHAPE_EXPECT[shapeKey];
  if (!exp.letters.length)
    return { verdict:'전환기', text:'직사각형은 특정 성향이 아니라 "변화 중"이라는 신호입니다. 지금의 검사 결과는 과도기의 스냅사진일 수 있으니, 반년 뒤 다시 비춰 보시길 권합니다.' };
  const hit = exp.letters.filter(L => mbtiType.includes(L)).length;
  const ratio = hit / exp.letters.length;
  if (ratio >= 0.67) return { verdict:'일치', text:`무의식(도형)과 의식(성향검사)이 같은 방향을 가리킵니다 — ${exp.label}의 기질이 겉과 속 모두에서 확인됩니다. 자신을 있는 그대로 쓰고 계신 것입니다.` };
  if (ratio > 0) return { verdict:'부분 일치', text:`무의식은 ${exp.label} 쪽으로 기울지만, 의식적 성향과는 결이 조금 다릅니다. 상황에 따라 두 얼굴을 바꿔 쓰는 유연함일 수도, 억누른 본성일 수도 있습니다.` };
  return { verdict:'보완', text:`무의식(${exp.label})과 의식(${mbtiType})이 서로 다른 방향을 가리킵니다. 이는 모순이 아니라 폭입니다 — 겉으로 쓰는 성향 아래, 아직 꺼내지 않은 카드가 잠들어 있습니다.` };
}

// ---------- 마무리 선언문 ----------
function generateDeclaration(name, saju, shape, color, mbti) {
  const parts = [];
  if (saju && !saju.error) {
    const il = ILGAN_DESC[saju.dayMaster.stem];
    parts.push(`${il.symbol.replace(/\(.+\)/, '').trim()}의 기운을 타고나`);
  }
  parts.push(`${shape.arche.split(' · ')[1]}으로 세상을 만나고`);
  parts.push(`${color.type}의 빛깔을 입고`);
  parts.push(`${mbti.typeName}(${mbti.type})의 걸음으로 걷는 사람`);
  return `${name} — ${parts.join(', ')}.`;
}

