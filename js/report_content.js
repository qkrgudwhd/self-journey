function analyzeSibseong(pillars) {
  const cnt = { 비겁:0, 식상:0, 재성:0, 관성:0, 인성:0 };
  for (const p of pillars) {
    for (const g of [p.stemGod, p.branchGod]) {
      if (!g || g.startsWith('일간')) continue;
      for (const [grp, info] of Object.entries(SIBSEONG_GROUP))
        if (info.members.includes(g)) cnt[grp]++;
    }
  }
  const sorted = Object.entries(cnt).sort((a, b) => b[1] - a[1]);
  const top = sorted[0], none = sorted.filter(([, c]) => c === 0).map(([g]) => g);
  return { counts: cnt, top: top[0], topCount: top[1], missing: none,
           topInfo: SIBSEONG_GROUP[top[0]] };
}

