function ohaengRelation(yearElem, myElem) {
  if (yearElem === myElem) return '비화';
  const yi = OHAENG_ORDER.indexOf(yearElem), mi = OHAENG_ORDER.indexOf(myElem);
  if ((yi + 1) % 5 === mi) return '지원';   // 세운이 나를 생
  if ((mi + 1) % 5 === yi) return '발산';   // 내가 세운을 생
  if ((yi + 2) % 5 === mi) return '단련';   // 세운이 나를 극
  return '도전';                             // 내가 세운을 극
}

