// 양력 월/일 → 별자리
function getWesternZodiac(month, day) {
  for (const z of WESTERN_ZODIAC) {
    const [fm, fd] = z.from, [tm, td] = z.to;
    if (fm <= tm) {
      if ((month === fm && day >= fd) || (month === tm && day <= td)) return z;
    } else {  // 염소자리 (12월→1월)
      if ((month === fm && day >= fd) || (month === tm && day <= td)) return z;
    }
  }
  return WESTERN_ZODIAC[9];   // 이론상 도달 불가 (안전망: 염소)
}

